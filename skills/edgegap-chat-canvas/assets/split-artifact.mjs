#!/usr/bin/env node
// Splits a claude.ai artifact (one HTML file) into the rules the Edgegap server runs.
//
//   node tools/split-artifact.mjs artifact/star-snatch.html            writes client/rules.js
//   node tools/split-artifact.mjs artifact/star-snatch.html --check    fails if client/rules.js is stale
//   node tools/split-artifact.mjs artifact/star-snatch.html --page      also writes client/index.html (first time only)
//
// The artifact keeps every game rule between two exact lines:
//   /* RULES:BEGIN */
//   ...plain functions and values, no window, document, canvas, audio, timers, no export...
//   /* RULES:END */
// The artifact itself stays unchanged, so it still plays in the claude.ai preview and you can paste
// it back into Claude for more changes. This script copies the block into an ES module and exports
// every top-level name, so the Node.js server and the online page run the exact same rules.
//
// --page turns the artifact into the online page's starting point: the block is removed and the
// script that held it becomes a module that imports the names from ./rules.js. Edit that page
// afterwards (Find match, online mode); later runs only refresh client/rules.js.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";

const BEGIN = "/* RULES:BEGIN */";
const END = "/* RULES:END */";
const REQUIRED = ["createWorld", "addPlayer", "removePlayer", "setInput", "step", "botInput"];
// Browser-only things that would crash or misbehave on the server.
// (Property names such as p.location are fine: only bare names count.)
const FORBIDDEN = /(?<![.\w$])(window|document|globalThis|self|navigator|location|localStorage|sessionStorage|canvas|getContext|Image|Audio|AudioContext|requestAnimationFrame|cancelAnimationFrame|setTimeout|setInterval|clearTimeout|clearInterval|performance|fetch|XMLHttpRequest|WebSocket|alert|console|import|export|require)\b/;

const args = process.argv.slice(2);
const flags = new Set(args.filter((a) => a.startsWith("--")));
const [input] = args.filter((a) => !a.startsWith("--"));
const outDir = args.includes("--out") ? args[args.indexOf("--out") + 1] : "client";
if (!input) {
  console.error("Usage: node tools/split-artifact.mjs <artifact.html> [--check] [--page] [--out client]");
  process.exit(2);
}

const html = readFileSync(input, "utf8").replace(/\r\n/g, "\n");
const fail = (msg) => {
  console.error(`split-artifact: ${msg}`);
  process.exit(1);
};

// ---- find the block ------------------------------------------------------------------------------
const b = html.indexOf(BEGIN);
const e = html.indexOf(END);
if (b < 0 || e < 0) fail(`markers not found: the artifact needs the exact lines ${BEGIN} and ${END}`);
if (html.indexOf(BEGIN, b + 1) >= 0 || html.indexOf(END, e + 1) >= 0) fail("markers appear more than once");
if (e < b) fail(`${END} comes before ${BEGIN}`);
const block = html.slice(b + BEGIN.length, e).replace(/^\n/, "").replace(/\s+$/, "") + "\n";

// ---- check it is server-safe ---------------------------------------------------------------------
const code = stripCommentsAndStrings(block);
const bad = [];
code.split("\n").forEach((line, i) => {
  const m = line.match(FORBIDDEN);
  if (m) bad.push(`line ${i + 1} of the block: "${m[1]}" (${block.split("\n")[i].trim().slice(0, 70)})`);
});
if (bad.length) fail(`the rules block uses browser-only or module code:\n  ${bad.join("\n  ")}\nAsk Claude to move it outside the block.`);

// ---- top-level names -------------------------------------------------------------------------------
const names = topLevelNames(code);
const missing = REQUIRED.filter((n) => !names.includes(n));
if (missing.length) fail(`the rules block does not define ${missing.join(", ")}`);

const rel = relative(outDir, input).replace(/\\/g, "/");
const rules =
  `// GENERATED by tools/split-artifact.mjs from ${input.replace(/\\/g, "/")}: do not edit here.\n` +
  `// Change the rules in the artifact (or in claude.ai), then run: npm run split\n` +
  `// The page (online mode) and the Edgegap server (server/game.js) both import this file.\n\n` +
  block +
  `\nexport { ${names.join(", ")} };\n`;

const rulesPath = join(outDir, "rules.js");
if (flags.has("--check")) {
  const current = existsSync(rulesPath) ? readFileSync(rulesPath, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== rules) fail(`${rulesPath} is out of date with ${input}: run npm run split and commit the result`);
  console.log(`${rulesPath} matches ${input} (${names.length} exports)`);
  process.exit(0);
}

mkdirSync(outDir, { recursive: true });
writeFileSync(rulesPath, rules);
console.log(`wrote ${rulesPath}: ${names.join(", ")}`);

if (flags.has("--page")) {
  const pagePath = join(outDir, "index.html");
  if (existsSync(pagePath)) fail(`${pagePath} exists already; --page only creates it once (delete it to start over)`);
  // The <script> that holds the block becomes a module importing the rules.
  const open = html.lastIndexOf("<script", b);
  const openEnd = html.indexOf(">", open) + 1;
  if (open < 0 || !/^<script\s*>$/i.test(html.slice(open, openEnd))) fail("the block must sit in a plain <script> tag for --page");
  const page =
    html.slice(0, open) +
    `<script type="module">\nimport { ${names.join(", ")} } from "./rules.js";\n` +
    html.slice(openEnd, b).replace(/^\n/, "") +
    `/* rules: ./rules.js (generated from ${rel}) */` +
    html.slice(e + END.length);
  writeFileSync(pagePath, page);
  console.log(`wrote ${pagePath} (module script importing ./rules.js)`);
}

// ---- helpers -------------------------------------------------------------------------------------

/** Blanks out comments and string contents (keeps line breaks), so checks only see code. */
function stripCommentsAndStrings(src) {
  let out = "";
  for (let i = 0; i < src.length; i++) {
    const c = src[i];
    const n = src[i + 1];
    if (c === "/" && n === "/") {
      while (i < src.length && src[i] !== "\n") i++;
      out += "\n";
    } else if (c === "/" && n === "*") {
      i += 2;
      while (i < src.length && !(src[i] === "*" && src[i + 1] === "/")) out += src[i++] === "\n" ? "\n" : "";
      i++;
    } else if (c === '"' || c === "'" || c === "`") {
      out += c;
      i++;
      while (i < src.length && src[i] !== c) {
        if (src[i] === "\\") i++;
        else if (src[i] === "\n") out += "\n";
        i++;
      }
      out += c;
    } else out += c;
  }
  return out;
}

/** Names declared at depth 0: function, class, var, let, const (plain identifiers). */
function topLevelNames(src) {
  const found = [];
  let depth = 0;
  let line = "";
  const flush = () => {
    const m = line.match(/^\s*(?:async\s+)?(?:function\*?|class)\s+([A-Za-z_$][\w$]*)/) || line.match(/^\s*(?:var|let|const)\s+([A-Za-z_$][\w$]*)/);
    if (m && !found.includes(m[1])) found.push(m[1]);
    // var a = 1, b = 2;  on one line
    const multi = line.match(/^\s*(?:var|let|const)\s+(.*)$/);
    if (multi) for (const part of multi[1].split(",")) {
      const id = part.match(/^\s*([A-Za-z_$][\w$]*)\s*(=|;|$)/);
      if (id && !found.includes(id[1]) && !/[({[]/.test(part.split("=")[0])) found.push(id[1]);
    }
    line = "";
  };
  for (const c of src) {
    if (depth === 0) line += c;
    if (c === "{" || c === "(" || c === "[") depth++;
    else if (c === "}" || c === ")" || c === "]") depth--;
    if (c === "\n" && depth === 0) flush();
  }
  flush();
  return found;
}
